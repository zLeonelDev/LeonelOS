void font_init() {
    debug_log("Font: 8x8 bitmap loaded\n");
}

const u8* font_glyph(u8 c) {
    return g_font_data[c & 0x7F];
}

u32 font_glyph_width(u8 c) { (void)c; return FONT_GLYPH_W; }
u32 font_glyph_height(u8 c) { (void)c; return FONT_GLYPH_H; }

u32 font_string_width(const char* s) {
    u32 w = 0;
    if (!s) return 0;
    while (*s) { w += FONT_GLYPH_W; s++; }
    return w;
}

u32 font_string_height(const char* s) {
    (void)s;
    return FONT_GLYPH_H;
}

void font_draw_char(u32 x, u32 y, u8 c, u32 fg, u32 bg) {
    const u8* glyph = g_font_data[c & 0x7F];
    for (u32 row = 0; row < FONT_GLYPH_H; row++) {
        u8 bits = glyph[row];
        for (u32 col = 0; col < FONT_GLYPH_W; col++) {
            u32 color = (bits & (0x80 >> col)) ? fg : bg;
            framebuffer_set_pixel(x + col, y + row, color);
        }
    }
}

void font_draw_string(u32 x, u32 y, const char* s, u32 fg, u32 bg) {
    if (!s) return;
    while (*s) {
        font_draw_char(x, y, (u8)*s, fg, bg);
        x += FONT_GLYPH_W;
        s++;
    }
}
